#ifndef __ERRORCODE_H__
#define __ERRORCODE_H__

// ============================================================
// GameDev 项目错误码
// ============================================================
//
// 使用 enum class 而不是普通 enum：
// 1. 强类型，避免错误码和其他整数/枚举意外混用
// 2. 需要明确写 GameError::xxx，可读性更好
// 3. 不会把枚举成员污染到全局作用域
//
// 例如：
//
//     GameError error = GameError::SdlInitFailed;
//
//     if (error != GameError::None)
//     {
//         // 发生错误
//     }
// ============================================================

enum class GameError
{
    // --------------------------------------------------------
    // 操作成功
    // --------------------------------------------------------

    None = 0,


    // --------------------------------------------------------
    // SDL 初始化相关错误
    // --------------------------------------------------------

    SdlInitFailed,


    // --------------------------------------------------------
    // 窗口相关错误
    // --------------------------------------------------------

    WindowCreationFailed,


    // --------------------------------------------------------
    // Renderer 相关错误
    // --------------------------------------------------------

    RendererCreationFailed,


    // --------------------------------------------------------
    // 运行期渲染相关错误
    // --------------------------------------------------------

    RenderingFailed,
};


#endif // !__ERRORCODE_H__


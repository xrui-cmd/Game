#ifndef __SAVEDATA_H__
#define __SAVEDATA_H__

// ============================================================
// SaveData：最佳战绩存档的读写（game 层，纯文件 IO 工具类）
// ============================================================
//
// 本批改造（SaveData 重构）：存档语义由「最高分（单一整数）」升级为
// 「最佳战绩（三项纪录）」——最高击杀 / 最高等级 / 最长存活（秒）。
// 类名与文件路径保持不变（见下），接口整体换成三项纪录的读写。
//
// 存储位置（沿用既有约定，关键设计）：
//   <SDL_GetPrefPath("GameDev", "CoinRush")>/highscore.txt
//   SDL_GetPrefPath 返回「每用户 + 每应用」专属的可写数据目录
//   （Windows 下形如 C:\Users\<用户>\AppData\Roaming\GameDev\CoinRush\），
//   首次调用时 SDL 会自动创建目录，返回值保证以路径分隔符结尾。
//
// 为什么文件名仍叫 highscore.txt（而不是改名）？
//   老玩家机器上已存在旧格式文件（内容 "highscore=123"）。沿用同一路径：
//     1. 首次读取时旧内容被按「无记录」处理（见容错契约），不会崩；
//     2. 首次写盘即用新格式覆盖旧文件——升级后不会留下两份互相打架的
//        存档文件，也不需要任何迁移代码；
//     3. 用户数据目录、清理习惯、路径引用全部保持不变。
//
// 文件格式：多行 key=value 文本（每行一项，行尾 \n）：
//   best_kills=N     最高击杀数
//   best_level=N     最高等级
//   best_time=N      最长存活整秒数
//   - 行序不敏感、行数不敏感：认得的键就取值，空行/注释性垃圾行忽略；
//   - 用整秒：与 HUD/结算的 mm:ss 展示口径一致（展示即截断到整秒）。
//
// 容错契约（与项目「资源缺失不崩」的一贯策略一致）：
//   - 读：文件缺失 / 旧 highscore 格式 / 垃圾内容 → 记录警告并返回
//     「无记录」（三项全 0）；单个键值损坏 → 该键按 0 计，其余键照读；
//   - 写：拿不到目录 / 写盘失败 → 记录警告并返回 false；
//   两种情况都不抛异常、不中断游戏。
//
// 读写时机（玩法侧约定，实现在 PlayScene）：
//   - 读：进入对局（PlayScene::onEnter）时读一次，作为本局比较基准；
//   - 写：仅完整对局（生命归零）结算时，比较后若有新纪录才覆盖写入；
//     中途 M 退出不计——半途而废的局不参与任何纪录。
// ============================================================

// 最佳战绩三项纪录（值语义：读出来一份完整快照，调用方持有后随意比较）
struct BestRecord
{
    int kills = 0;   // 最高击杀数（0 = 无记录）
    int level = 0;   // 最高等级（0 = 无记录；对局中等级最小为 1，故首局决胜于 0）
    int seconds = 0; // 最长存活（整秒；0 = 无记录）

    // 是否「无记录」：三项全 0。菜单据此显示「暂无」而不是一排 0。
    // 正常完整的首局必然产生 level >= 1、seconds >= 1，因此首局写盘后必不为空
    bool empty() const { return kills <= 0 && level <= 0 && seconds <= 0; }
};

class SaveData
{
public:
    // 读取最佳战绩。文件缺失（首次运行）/ 旧格式 / 内容损坏时记录警告并
    // 返回全 0 的无记录快照——调用方永远拿到合法数值，无需自行容错
    static BestRecord load();

    // 覆盖写入三项纪录（三行 key=value）。返回是否成功：
    // 失败时记录警告并返回 false，游戏侧不受影响（内存里仍按新纪录展示，
    // 只是下次启动会丢失该纪录）
    static bool save(const BestRecord& record);
};

#endif // !__SAVEDATA_H__
